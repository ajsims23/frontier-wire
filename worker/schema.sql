CREATE TABLE IF NOT EXISTS subscribers (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, follows TEXT NOT NULL, labels TEXT, frequency TEXT NOT NULL,
  confirmed INTEGER NOT NULL DEFAULT 0, ctoken TEXT, utoken TEXT NOT NULL, pending TEXT, created TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS sub_ctoken ON subscribers (ctoken);
CREATE INDEX IF NOT EXISTS sub_utoken ON subscribers (utoken);
CREATE TABLE IF NOT EXISTS sent (sub_id TEXT NOT NULL, event_key TEXT NOT NULL, PRIMARY KEY (sub_id, event_key));
CREATE TABLE IF NOT EXISTS queue (id INTEGER PRIMARY KEY AUTOINCREMENT, sub_id TEXT NOT NULL, event TEXT NOT NULL, created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS usage (day TEXT NOT NULL, kind TEXT NOT NULL, who TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, kind, who));
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
