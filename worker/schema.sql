CREATE TABLE IF NOT EXISTS subscribers (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, follows TEXT NOT NULL, labels TEXT, frequency TEXT NOT NULL,
  confirmed INTEGER NOT NULL DEFAULT 0, ctoken TEXT, utoken TEXT NOT NULL, pending TEXT, created TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS sub_ctoken ON subscribers (ctoken);
CREATE INDEX IF NOT EXISTS sub_utoken ON subscribers (utoken);
CREATE TABLE IF NOT EXISTS sent (sub_id TEXT NOT NULL, event_key TEXT NOT NULL, PRIMARY KEY (sub_id, event_key));
CREATE TABLE IF NOT EXISTS queue (id INTEGER PRIMARY KEY AUTOINCREMENT, sub_id TEXT NOT NULL, event TEXT NOT NULL, created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS usage (day TEXT NOT NULL, kind TEXT NOT NULL, who TEXT NOT NULL, n INTEGER NOT NULL, PRIMARY KEY (day, kind, who));
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT);
-- community feedback (worker/src/feedback.js)
CREATE TABLE IF NOT EXISTS suggestions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL, body TEXT NOT NULL DEFAULT '', category TEXT NOT NULL DEFAULT 'feature',
  status TEXT NOT NULL DEFAULT 'open', public INTEGER NOT NULL DEFAULT 1, held INTEGER NOT NULL DEFAULT 0, source TEXT NOT NULL DEFAULT 'board',
  name TEXT, author TEXT NOT NULL, ip TEXT NOT NULL, votes INTEGER NOT NULL DEFAULT 0, comments INTEGER NOT NULL DEFAULT 0,
  note TEXT, created TEXT NOT NULL, updated TEXT NOT NULL, done TEXT
);
CREATE INDEX IF NOT EXISTS sug_board ON suggestions (public, held, votes);
CREATE INDEX IF NOT EXISTS sug_author ON suggestions (author);
CREATE TABLE IF NOT EXISTS votes (sid INTEGER NOT NULL, voter TEXT NOT NULL, ip TEXT NOT NULL, created TEXT NOT NULL, PRIMARY KEY (sid, voter));
CREATE INDEX IF NOT EXISTS votes_voter ON votes (voter);
CREATE INDEX IF NOT EXISTS votes_created ON votes (created);
CREATE TABLE IF NOT EXISTS fcomments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, sid INTEGER NOT NULL, body TEXT NOT NULL, name TEXT, author TEXT NOT NULL, ip TEXT NOT NULL,
  held INTEGER NOT NULL DEFAULT 0, team INTEGER NOT NULL DEFAULT 0, created TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS fcomments_sid ON fcomments (sid);
CREATE TABLE IF NOT EXISTS watchers (sid INTEGER NOT NULL, email TEXT NOT NULL, told TEXT NOT NULL DEFAULT 'open', created TEXT NOT NULL, PRIMARY KEY (sid, email));
CREATE TABLE IF NOT EXISTS reports (week TEXT PRIMARY KEY, created TEXT NOT NULL, data TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending');
CREATE TABLE IF NOT EXISTS picks (
  week TEXT NOT NULL, sid INTEGER NOT NULL, rank INTEGER NOT NULL, reason TEXT NOT NULL, score REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', decided TEXT, PRIMARY KEY (week, sid)
);
CREATE TABLE IF NOT EXISTS log (id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, level TEXT NOT NULL, kind TEXT NOT NULL, msg TEXT NOT NULL);
-- API usage and limits (admin dashboard "Usage & limits"; see src/apiusage.js)
CREATE TABLE IF NOT EXISTS api_usage (day TEXT NOT NULL, service TEXT NOT NULL, model TEXT NOT NULL, source TEXT NOT NULL,
  requests INTEGER NOT NULL DEFAULT 0, ok INTEGER NOT NULL DEFAULT 0, limited INTEGER NOT NULL DEFAULT 0, busy INTEGER NOT NULL DEFAULT 0,
  failed INTEGER NOT NULL DEFAULT 0, tokens INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (day, service, model, source));
CREATE TABLE IF NOT EXISTS api_state (service TEXT NOT NULL, k TEXT NOT NULL, v TEXT NOT NULL, at TEXT NOT NULL, PRIMARY KEY (service, k));
